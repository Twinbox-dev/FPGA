// 测试顶层：例化板级 sd_card_bmp（新 FAT32 版），暴露写口/按键/状态供 C++ 驱动
module board_top (
    input  wire        clk,
    input  wire        rst,
    input  wire        key_next,
    input  wire        key_auto,
    input  wire        key_prev,
    // ---- SIM_FAST 直连扇区服务器（fast_en=1 选中）----
    input  wire        fast_en,
    input  wire [7:0]  fast_byte,
    input  wire        fast_val,
    output wire [31:0] fast_lba,
    output wire [9:0]  fast_idx,
    output wire        fast_serving,
    input  wire        write_req_ack,
    input  wire        write_finish_toggle,
    output wire        write_req,
    output wire        write_en,
    output wire [31:0] write_data,
    output wire [20:0] write_len,
    output wire        display_valid,
    output wire [1:0]  disp_buf_idx,
    input  wire [1:0]  effect_mode,
    input  wire        transition_done_toggle,
    output wire        transition_start_toggle,
    output wire        transition_target_buf,
    output wire [1:0]  transition_mode_latched,
    output wire        transition_prev_latched,
    output wire [1:0]  write_buf_idx,
    output wire [3:0]  state_code,
    // ---- 音频扫描观测（S1）----
    output wire [7:0]  aud_smp,
    output wire        aud_sval,
    output wire        aud_item_done,
    output wire        aud_scan_done,
    output wire        wav_hdr_ok,
    output wire        wav_fmt_err,
    output wire [31:0] wav_data_bytes,
    // ---- 音频播放 / 读口（S3）----
    input  wire        rd_req_ack,
    input  wire        rd_finish,
    input  wire [31:0] rd_data,
    output wire        aud_valid,
    output wire [23:0] aud_l,
    output wire [23:0] aud_r,
    output wire        aud_play_done,
    output wire        aud_underrun,
    output wire        aud_tick,
    output wire        aud_pair_on,
    output wire        rd_req,
    output wire        rd_en,
    output wire [1:0]  rd_addr_idx,
    output wire [20:0] rd_len,
    output wire        SD_nCS,
    output wire        SD_DCLK,
    output wire        SD_MOSI,
    input  wire        SD_MISO,
    // ---- 播放列表转储（'L' 调试命令，S11）----
    input  wire        pl_dump_start,
    output wire [63:0] pl_pkt,
    output wire        pl_pkt_val
);
`ifdef FPGA_LEAN_LIST_DIAG
    localparam ENABLE_LIST_DIAG_BUILD = 1'b0;
`else
    localparam ENABLE_LIST_DIAG_BUILD = 1'b1;
`endif
    sd_card_bmp #(.ENABLE_LIST_DIAG(ENABLE_LIST_DIAG_BUILD)) u_sd_card_bmp_m0 (
        .clk                 (clk),
        .rst                 (rst),
        .key_next            (key_next),
        .key_auto            (key_auto),
        .key_prev            (key_prev),
        .auto_period_s       (4'd1),   // 主仿真固定 1s（S7 用例语义）
        .fast_en             (fast_en),
        .fast_byte           (fast_byte),
        .fast_val            (fast_val),
        .fast_lba            (fast_lba),
        .fast_idx            (fast_idx),
        .fast_serving        (fast_serving),
        .img_idx_out         (),
        .img_wav_out         (),
        .bmp_width           (16'd1280),
        .bmp_height          (16'd720),
        .display_valid       (display_valid),
        .state_code          (state_code),
        .write_finish_toggle (write_finish_toggle),
        .write_buf_idx       (write_buf_idx),
        .disp_buf_idx        (disp_buf_idx),
        .effect_mode         (effect_mode),
        .transition_start_toggle (transition_start_toggle),
        .transition_target_buf (transition_target_buf),
        .transition_mode_latched (transition_mode_latched),
        .transition_prev_latched (transition_prev_latched),
        .transition_done_toggle (transition_done_toggle),
        .write_req           (write_req),
        .write_req_ack       (write_req_ack),
        .write_en            (write_en),
        .write_data          (write_data),
        .write_len           (write_len),
        .aud_smp             (aud_smp),
        .aud_sval            (aud_sval),
        .aud_item_done       (aud_item_done),
        .aud_scan_done       (aud_scan_done),
        .wav_hdr_ok          (wav_hdr_ok),
        .wav_fmt_err         (wav_fmt_err),
        .wav_data_bytes      (wav_data_bytes),
        .aud_valid           (aud_valid),
        .aud_l               (aud_l),
        .aud_r               (aud_r),
        .aud_play_done       (aud_play_done),
        .aud_underrun        (aud_underrun),
        .aud_tick            (aud_tick),
        .aud_pair_on         (aud_pair_on),
        .rd_req              (rd_req),
        .rd_en               (rd_en),
        .rd_addr_idx         (rd_addr_idx),
        .rd_len              (rd_len),
        .rd_req_ack          (rd_req_ack),
        .rd_finish           (rd_finish),
        .rd_data             (rd_data),
        .SD_nCS              (SD_nCS),
        .SD_DCLK             (SD_DCLK),
        .SD_MOSI             (SD_MOSI),
        .SD_MISO             (SD_MISO),
        .pl_dump_start       (pl_dump_start),
        .pl_pkt              (pl_pkt),
        .pl_pkt_val          (pl_pkt_val)
    );
endmodule
