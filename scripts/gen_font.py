def row_to_byte(row: str) -> int:
    """一行 8 字符 '#'/'.' -> 8bit，最左字符 = bit7。"""
    assert len(row) == 8, f"row length must be 8, got {len(row)}: {row!r}"
    b = 0
    for col, ch in enumerate(row):
        if ch == '#':
            b |= 1 << (7 - col)
        elif ch != '.':
            raise ValueError(f"bad glyph char {ch!r} in {row!r}")
    return b


def build_mem() -> list[int]:
    """按 raw-ASCII 寻址生成 2048 个 word（address = ascii*16 + row）。"""
    mem = [0] * 2048
    for ascii_code in range(128):
        ch = chr(ascii_code)
        if ch not in FONT:
            continue  # 未收录字符保持 0x00（空白）
        for row in range(16):
            mem[ascii_code * 16 + row] = row_to_byte(FONT[ch][row])
    return mem


def main():
    ap = argparse.ArgumentParser()
    default_out = Path(__file__).resolve().parents[1] / 'board/user_source/hdl_source/SD/font.mem'
    ap.add_argument('--out', default=str(default_out), help='output path')
    args = ap.parse_args()

    # 校验每个字形都是 16 行
    for ch, rows in FONT.items():
        assert len(rows) == 16, f"glyph {ch!r} has {len(rows)} rows, need 16"

    mem = build_mem()
    with open(args.out, 'w', newline='\n') as f:
        for w in mem:
            f.write(f"{w:02X}\n")

    n_used = sum(1 for c in range(128) if chr(c) in FONT)
    print(f"font.mem written: {args.out}")
    print(f"  total words = {len(mem)} (2048)")
    print(f"  glyphs      = {n_used}")
    # 抽查 'A'(0x41) 与 '0'(0x30) 首行
    for ch in ('A', '0', ':'):
        a = ord(ch) * 16
        print(f"  '{ch}' (0x{ord(ch):02X}) rows[0:3] = "
              f"{mem[a]:02X} {mem[a+1]:02X} {mem[a+2]:02X}")


if __name__ == '__main__':
    main()
